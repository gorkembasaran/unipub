const adminCopies: Record<"tr" | "en", typeof en> = {
  tr,
  en,
};

export type AdminCopy = typeof en;

export function formatAdminCopy(template: string, vars?: CopyVars) {
  if (!vars) return template;

  return Object.entries(vars).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function getAdminCopy(locale: string | Locale): AdminCopy {
  return adminCopies[String(locale).toLowerCase().startsWith("tr") ? "tr" : "en"];
}
