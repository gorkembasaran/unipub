async function loadPdfMake() {
  const [pdfMakeModule, pdfFontsModule] = await Promise.all([
    import("pdfmake/build/pdfmake"),
    import("pdfmake/build/vfs_fonts"),
  ]);

  const pdfMake = (pdfMakeModule.default ?? pdfMakeModule) as unknown as PdfMakeLike;
  const pdfFonts = (pdfFontsModule.default ?? pdfFontsModule) as Record<string, string>;
  pdfMake.addVirtualFileSystem(pdfFonts);
  return pdfMake;
}

export function createAuthorPdfDocumentDraft({
  author,
  publications,
  locale,
  t,
  currentDateFilterLabel,
}: ExportAuthorPublicationsPdfInput): AuthorPdfDocumentDraft {
  const labels = getDraftLabels(locale);
  const generatedAt = new Date();
  const profile = getAuthorProfileDetails(author);
  const profileDetails = compact(profile.detailParts).join(" • ");
  const authorInstitution = profile.primaryAffiliation ?? labels.missing;

  return {
    authorInfoTitle: labels.authorInfoTitle,
    authorLabel: labels.authorLabel,
    authorName: author.fullName,
    declaration: labels.declaration,
    details: profileDetails,
    detailsLabel: labels.detailsLabel,
    documentInfoTitle: labels.documentInfoTitle,
    doiLabel: labels.doiLabel,
    exportNote: labels.exportNote,
    filter: currentDateFilterLabel,
    filterLabel: labels.filterLabel,
    generatedAt: buildGeneratedAtLabel(locale, generatedAt),
    generatedAtLabel: labels.generatedAtLabel,
    institution: authorInstitution,
    institutionLabel: labels.institutionLabel,
    orcid: author.orcid?.trim() ?? "",
    orcidLabel: labels.orcidLabel,
    preparedBy: labels.preparedBy,
    publicationListTitle: labels.publicationListTitle,
    publications: publications.map((publication) => ({
      id: publication._id,
      authors: formatAuthors(publication) ?? labels.missing,
      citation: buildPublicationVenue(publication, locale, t) || labels.missing,
      doi: buildDoiValue(publication.doi)?.text ?? publication.doi?.trim() ?? "",
      keywords: buildPublicationKeywordsLine(publication, labels),
      metadata: buildPublicationMetadataLine(publication, locale, labels),
      title: publication.title,
      year: getPublicationYear(publication)
        ? String(getPublicationYear(publication))
        : labels.missing,
    })),
    rowAuthorsLabel: labels.rowAuthorsLabel,
    rowVenueLabel: labels.rowVenueLabel,
    subtitle: labels.subtitle,
    title: labels.title,
    total: String(publications.length),
    totalLabel: labels.totalLabel,
    yearLabel: labels.yearLabel,
  };
}

export async function downloadAuthorPdfDocumentDraft(
  draft: AuthorPdfDocumentDraft,
  locale: string,
) {
  const pdfMake = await loadPdfMake();
  const docDefinition = buildPdfDefinition(draft, locale);
  const fileBase = isTurkishLocale(locale)
    ? "akademik-yayin-dokumu"
    : "academic-publication-dossier";
  const fileName = [
    sanitizeFileNameSegment(draft.authorName || "author"),
    fileBase,
    new Date().toISOString().slice(0, 10),
  ]
    .filter(Boolean)
    .join("-")
    .concat(".pdf");

  pdfMake.createPdf(docDefinition).download(fileName);
}

export async function exportAuthorPublicationsPdf(
  input: ExportAuthorPublicationsPdfInput,
) {
  if (input.publications.length === 0) {
    throw new Error(
      isTurkishLocale(input.locale)
        ? "Dışa aktarılacak yayın bulunamadı."
        : "No publications available for export.",
    );
  }

  const draft = createAuthorPdfDocumentDraft(input);
  await downloadAuthorPdfDocumentDraft(draft, input.locale);
}
