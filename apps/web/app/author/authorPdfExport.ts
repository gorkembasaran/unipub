function sanitizeFileNameSegment(value: string) {
  return value
    .trim()
    .toLocaleLowerCase("tr-TR")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 64);
}

function buildDoiValue(doi?: string | null) {
  const trimmed = doi?.trim();
  if (!trimmed) {
    return null;
  }

  const normalized = trimmed.replace(/^https?:\/\/(dx\.)?doi\.org\//i, "");
  if (!normalized) {
    return null;
  }

  return {
    text: normalized,
    link: `https://doi.org/${normalized}`,
  };
}

function getVenuePartLabels(locale: string) {
  if (!isTurkishLocale(locale)) {
    return {
      volume: "Vol.",
      issue: "Issue",
      pages: "Pages",
    };
  }

  return {
    volume: "Cilt",
    issue: "Sayı",
    pages: "Sayfa",
  };
}

function buildPublicationVenue(publication: Publication, locale: string, t: TranslateFn) {
  const partLabels = getVenuePartLabels(locale);
  const parts = compact([
    publication.journal,
    publication.publisher,
    publication.volume ? `${partLabels.volume} ${publication.volume}` : undefined,
    publication.issue ? `${partLabels.issue} ${publication.issue}` : undefined,
    publication.pages ? `${partLabels.pages} ${publication.pages}` : undefined,
    formatPublicationDate(publication, locale, t),
  ]);

  return parts.join(" • ");
}

function buildGeneratedAtLabel(locale: string, date: Date) {
  return new Intl.DateTimeFormat(locale, {
    day: "2-digit",
    month: "long",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  }).format(date);
}

function buildSourceSummary(publication: Publication, missingLabel: string) {
  const labels = getPublicationSourceLinks(publication).map((item) => item.label);
  return labels.length > 0 ? labels.join(", ") : missingLabel;
}

function buildPublicationMetadataLine(
  publication: Publication,
  locale: string,
  labels: ReturnType<typeof getDraftLabels>,
) {
  const year = getPublicationYear(publication);
  const parts = compact([
    `${labels.sourcesLabel}: ${buildSourceSummary(publication, labels.missing)}`,
    publication.language ? `${labels.languageLabel}: ${publication.language}` : undefined,
    typeof publication.citationCount === "number"
      ? `${labels.citationsLabel}: ${publication.citationCount}`
      : undefined,
    publication.pmid ? `${labels.pmidLabel}: ${publication.pmid}` : undefined,
    year ? `${labels.yearLabel}: ${year}` : undefined,
  ]);

  return parts.join("  •  ");
}

function buildPublicationKeywordsLine(
  publication: Publication,
  labels: ReturnType<typeof getDraftLabels>,
) {
  const keywords = compact(publication.keywords ?? []).slice(0, 8);
  if (keywords.length === 0) {
    return "";
  }

  return `${labels.keywordsLabel}: ${keywords.join(", ")}`;
}

function buildInfoEntry(label: string, value: string): PdfMakeContent {
  return {
    stack: [
      {
        text: label,
        style: "metaLabel",
      },
      {
        text: value,
        style: "metaValue",
        margin: [0, 3, 0, 0],
      },
    ],
    margin: [0, 0, 0, 10],
  };
}

function buildPublicationCard(
  publication: AuthorPdfPublicationDraft,
  index: number,
  draft: AuthorPdfDocumentDraft,
): PdfMakeContent {
  const doi = buildDoiValue(publication.doi);
  const detailStack: PdfMakeContent[] = [
    {
      columns: [
        {
          width: 34,
          text: String(index + 1).padStart(2, "0"),
          style: "publicationIndex",
          alignment: "center",
        },
        {
          width: "*",
          stack: [
            {
              text: publication.title || "-",
              style: "publicationTitle",
              lineHeight: 1.18,
            },
            {
              text: `${draft.rowAuthorsLabel}: ${publication.authors || "-"}`,
              style: "publicationMeta",
              margin: [0, 6, 0, 0],
            },
            {
              text: `${draft.rowVenueLabel}: ${publication.citation || "-"}`,
              style: "publicationMeta",
              margin: [0, 4, 0, 0],
            },
          ],
        },
        {
          width: 62,
          stack: [
            {
              text: draft.yearLabel,
              style: "publicationYearLabel",
              alignment: "right",
            },
            {
              text: publication.year || "-",
              style: "publicationYearValue",
              alignment: "right",
              margin: [0, 3, 0, 0],
            },
          ],
        },
      ],
      columnGap: 12,
    },
  ];

  detailStack.push(
    doi
      ? {
          text: `${draft.doiLabel}: ${doi.text}`,
          style: "publicationLink",
          link: doi.link,
          margin: [0, 8, 0, 0],
        }
      : {
          text: `${draft.doiLabel}: ${publication.doi || "-"}`,
          style: "publicationMuted",
          margin: [0, 8, 0, 0],
        },
  );

  if (publication.metadata.trim()) {
    detailStack.push({
      text: publication.metadata,
      style: "publicationAux",
      margin: [0, 6, 0, 0],
    });
  }

  if (publication.keywords.trim()) {
    detailStack.push({
      text: publication.keywords,
      style: "publicationAux",
      margin: [0, 4, 0, 0],
    });
  }

  return {
    table: {
      widths: ["*"],
      body: [
        [
          {
            stack: detailStack,
            fillColor: index % 2 === 0 ? "#ffffff" : "#f8fafc",
            border: [true, true, true, true],
          },
        ],
      ],
    },
    layout: {
      hLineColor: () => "#dbe4f0",
      vLineColor: () => "#dbe4f0",
      paddingLeft: () => 12,
      paddingRight: () => 12,
      paddingTop: () => 12,
      paddingBottom: () => 12,
    },
    margin: [0, 0, 0, 10],
  };
}

